// Copies the extension's real stylesheets into the video project so the UI on screen is the
// product's own CSS (tokens, components, app glue, screen styles). @font-face rules are dropped:
// the video loads the same IBM Plex files from public/fonts (src/brand/fonts.ts).
// Also copies the HoneLENS icon set. Run automatically by `npm run typecheck` / `studio`.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
// Standalone copy of this folder: the product sources are not here, and the generated brand files
// are committed. Nothing to sync.
if (!existsSync(path.join(repo, 'src', 'styles'))) {
  console.log('No product sources next to video/; using the committed brand CSS and icons.');
  process.exit(0);
}
const out = path.resolve(here, '..', 'src', 'ui', 'css');
mkdirSync(out, { recursive: true });

const strip = css => css.replace(/@font-face\s*\{[^}]*\}/g, '');
const files = ['honelens-tokens.css', 'honelens-components.css', 'app.css'];
let all = '/* Generated by scripts/sync-brand.mjs from ../src/styles. Do not edit. */\n';
for (const f of files) all += `\n/* ${f} */\n` + strip(readFileSync(path.join(repo, 'src', 'styles', f), 'utf8'));
const screens = path.join(repo, 'src', 'styles', 'screens');
for (const f of readdirSync(screens).filter(n => n.endsWith('.css')).sort()) {
  all += `\n/* screens/${f} */\n` + strip(readFileSync(path.join(screens, f), 'utf8'));
}
// The video is always the light theme: neutralize the OS dark-mode query.
all = all.replace(/@media\s*\(prefers-color-scheme:\s*dark\)/g, '@media (prefers-color-scheme: no-preference-video)');
writeFileSync(path.join(out, 'honelens.css'), all);

// Icons: the ES module exports ICONS (inner SVG markup). Re-emit as TypeScript.
const iconsSrc = readFileSync(path.join(repo, 'src', 'ui', 'icons.js'), 'utf8');
const m = iconsSrc.match(/export const ICONS = Object\.freeze\((\{[\s\S]*?\n\})\);/);
if (!m) throw new Error('Could not find ICONS in src/ui/icons.js');
writeFileSync(path.join(here, '..', 'src', 'ui', 'icon-paths.ts'),
  '// Generated by scripts/sync-brand.mjs from ../src/ui/icons.js. Do not edit.\n' +
  `export const ICON_PATHS = ${m[1]} as const;\nexport type IconName = keyof typeof ICON_PATHS;\n`);
console.log('Synced brand CSS and icons into video/src/ui');
